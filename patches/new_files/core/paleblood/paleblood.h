// Paleblood (third_party/paleblood): a functional decompilation of Bloodborne, whose verified
// C++ replacements for the game's own functions are compiled into the wasm build. When the game
// running is the one they're written for, each replaced function's entry gets a jump to its
// replacement, so that function runs as compiled wasm instead of through the x86-64 interpreter -
// the same patch Paleblood's own runtime makes natively. Replacements reach the rest of the game
// through Paleblood's runtime interface, which this port implements on the interpreter
// (core/paleblood/port/runtime/*.h).

#pragma once

#include <span>
#include <string_view>
#include "common/types.h"

namespace Core::Paleblood {

struct Hook {
    u32 address; // PS4 virtual address of the original, with the executable at 0x400000
    u32 size;    // the original's size in bytes (Paleblood's symbols/functions.csv)
    const char* name;
    u64 (*thunk)(); // the replacement's HLE thunk address (core/interpreter/hle.h)
};

// Paleblood's target: Bloodborne CUSA03173 (EU) with update 1.09 merged.
constexpr std::string_view kTargetSerial = "CUSA03173";
constexpr std::string_view kTargetAppVer = "01.09";

// The replacements compiled into this build, from Paleblood's game/hooks.csv (generated by
// tools/paleblood_port.py).
std::span<const Hook> GameHooks();

// Points each hook's original at its replacement in the executable mapped at `image` (`size`
// bytes). Skips (and logs) hooks that don't fit: an original shorter than the 14-byte jump or
// outside the image. BB_HOOK_SKIP (Paleblood's variable: comma-separated addresses or names)
// leaves hooks out. Returns how many were installed.
u32 InstallHooks(u8* image, u64 size, std::span<const Hook> hooks);

// Called once the game's executable is loaded and relocated, before its entry runs. Installs
// GameHooks() when the game is Paleblood's target; SHADPS4_PALEBLOOD=0 turns that off.
void OnGameLoaded(VAddr eboot_base, u64 eboot_size, std::string_view serial,
                  std::string_view app_ver);

} // namespace Core::Paleblood

// The calling guest thread's thread pointer (fs:[0]): Paleblood's engine::thread_pointer() reads
// it with an x86 segment load natively; the build rewrites that read into a call to this.
extern "C" unsigned char* paleblood_guest_thread_pointer();
