#!/usr/bin/env bash
# Assembles guest_code.s (x86-64, Intel syntax) with LLVM and writes guest_code.inc: the raw
# bytes plus each function's offset, for test_main.cpp. Rerun after editing guest_code.s.
# Needs a clang with the x86 backend (Xcode's or a full LLVM; Emscripten's bundled clang only
# targets wasm) and llvm-objcopy/llvm-nm (Emscripten ships those).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
cc=${X86_CLANG:-clang}
llvm=${LLVM_BIN:-$(em-config LLVM_ROOT)}
tmp=$(mktemp -d)
"$cc" -target x86_64-linux-gnu -c "$here/guest_code.s" -o "$tmp/t.o"
"$llvm/llvm-objcopy" -O binary --only-section=.text "$tmp/t.o" "$tmp/t.bin"
{
  echo "// Generated by gen_guest_code.sh from guest_code.s - do not edit."
  echo "static const unsigned char kGuestCode[] = {"
  xxd -i < "$tmp/t.bin"
  echo "};"
  "$llvm/llvm-nm" "$tmp/t.o" | awk '$2 == "t" && $3 ~ /^f_/ { printf "static constexpr unsigned long long k_%s = 0x%s;\n", substr($3, 3), $1 }'
} > "$here/guest_code.inc"
rm -rf "$tmp"
echo "wrote $here/guest_code.inc"
